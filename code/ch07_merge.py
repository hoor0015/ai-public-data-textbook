# 7주차 병합 예제: 2023년 시군구 인구 데이터와 2013년 합계출산율 데이터 병합
# 실행: cd ~/default-uv-env && PYTHONIOENCODING=utf-8 VIRTUAL_ENV= uv run python "<이 파일 경로>"
from pathlib import Path

import pandas as pd

DATA = Path(__file__).resolve().parent.parent / "data"

# ---------------------------------------------------------------- 1. 읽기
d2023 = pd.read_csv(DATA / "sigungu_2023.csv")          # 229행: 2023년 시군구 인구 지표
d2013 = pd.read_csv(DATA / "sigungu_tfr_2013.csv")      # 264행: 2013년 시군구 합계출산율

print("2023년 데이터:", d2023.shape[0], "행 /", "2013년 데이터:", d2013.shape[0], "행")

# ---------------------------------------------------------------- 2. 진단 병합
# 병합 키는 (시도, 시군구) 두 열의 조합이다. 시군구 이름만 쓰면
# 서울 중구, 부산 중구, 대구 중구 등이 서로 뒤엉킨다 (본문 1.5절 참고).
# how="outer"와 indicator=True로 먼저 "어디가 안 맞는지"부터 확인한다.
diag = d2023.merge(d2013, on=["시도", "시군구"], how="outer", indicator=True)

print("\n[진단] 병합 결과 분포")
print(diag["_merge"].value_counts())
print("\n[진단] 2023년에만 있는 시군구 (left_only)")
print(diag.loc[diag["_merge"] == "left_only", ["시도", "시군구"]].to_string(index=False))
print("\n[진단] 2013년에만 있는 시군구 (right_only)")
print(diag.loc[diag["_merge"] == "right_only", ["시도", "시군구"]].to_string(index=False))

# ---------------------------------------------------------------- 3. 불일치 해소
# 진단 결과 (실행해 보면 다음이 확인된다):
#  - left_only 1건: 인천 미추홀구. 2013년에는 "인천 남구"였다 (2018년 명칭 변경).
#  - right_only 36건:
#    (1) 일반구 33건: 수원시 장안구, 성남시 분당구, 창원시 진해구, 전주시 완산구 등.
#        2013년 파일은 대도시 안의 일반구를 별도 행으로 함께 담고 있는데,
#        2023년 파일은 시 단위로만 기록했다. 시 단위 행(수원시, 성남시 등)은
#        양쪽에 다 있으므로, 일반구 행은 병합에서 빠져도 정보 손실이 아니다.
#    (2) 충북 청원군: 2014년 청주시와 통합되어 2023년에는 존재하지 않는다.
#    (3) 세종 세종시: 2013년 파일에 "세종특별자치시"와 "세종시"가 중복 수록되어
#        있고, 2023년 파일 표기는 "세종특별자치시"다. 중복 행은 병합에서 빠진다.

d2013_fix = d2013.copy()
# 인천 남구 -> 미추홀구: 같은 지역의 옛 이름이므로 현재 이름으로 바꿔 살린다.
mask = (d2013_fix["시도"] == "인천") & (d2013_fix["시군구"] == "남구")
d2013_fix.loc[mask, "시군구"] = "미추홀구"

# ---------------------------------------------------------------- 4. 본 병합
# 2023년 229개 시군구를 기준(왼쪽)으로 한다. validate로 1:1 대응을 강제하여
# 키가 중복이면 병합이 조용히 부풀지 않고 즉시 오류를 내게 한다.
merged = d2023.merge(d2013_fix, on=["시도", "시군구"], how="left",
                     validate="one_to_one")

# ---------------------------------------------------------------- 5. 검증
assert len(merged) == len(d2023), "병합 후 행 수가 달라졌다"
n_na = merged["합계출산율_2013"].isna().sum()
print("\n[검증] 병합 후 행 수:", len(merged), "(기준 데이터와 동일해야 함)")
print("[검증] 2013년 출산율이 붙지 않은 시군구:", n_na, "곳")
print(merged.loc[merged["합계출산율_2013"].isna(), ["시도", "시군구"]].to_string(index=False))
# 실행해 보면 미추홀구 수정 덕분에 229곳 모두 2013년 값이 붙는다 (0곳).
# 다만 두 곳은 여전히 해석에 주의가 필요하다.
#  - 경북 군위군: 2023년 쪽 합계출산율이 결측이다 (2023년 7월 대구 편입).
#  - 충북 청주시: 2013년 값은 통합(2014년) 전의 옛 청주시 값이므로
#    2023년의 통합 청주시와 관할 범위가 다르다.

# 표본 대조: 원본 파일에서 직접 확인한 값과 병합 결과를 비교한다.
samples = [("서울", "종로구"), ("경북", "의성군"), ("인천", "미추홀구")]
print("\n[검증] 표본 대조")
for sido, sgg in samples:
    row = merged[(merged["시도"] == sido) & (merged["시군구"] == sgg)]
    print(f"  {sido} {sgg}: 2013년 {row['합계출산율_2013'].iloc[0]}"
          f" -> 2023년 {row['합계출산율'].iloc[0]}")

# ---------------------------------------------------------------- 6. 저장
out = DATA / "sigungu_tfr_2013_2023.csv"
merged.to_csv(out, index=False, encoding="utf-8-sig")
print("\n저장:", out.name, "/", len(merged), "행", len(merged.columns), "열")
